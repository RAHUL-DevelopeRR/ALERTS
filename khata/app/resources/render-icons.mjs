// Regenerates the launcher icon assets from icon-shapes.mjs.
//   node resources/render-icons.mjs
// Writes resources/icon.svg (512 px legacy-style master), android/app/src/main/res/drawable/ic_launcher_foreground.xml,
// drawable/ic_launcher_monochrome.xml and legacy mipmap PNGs (square + round) for mdpi..xxxhdpi.
// PNG rendering uses Playwright's Chromium (PLAYWRIGHT_PATH overrides the module location).
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FOREGROUND, MONOCHROME, GREEN } from './icon-shapes.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const res = join(here, '..', 'android', 'app', 'src', 'main', 'res');

function svgLayers(layers) {
  return layers
    .map((l) =>
      l.fill
        ? `<path d="${l.d}" fill="${l.fill}"/>`
        : `<path d="${l.d}" fill="none" stroke="${l.stroke}" stroke-width="${l.width}" stroke-linecap="round" stroke-linejoin="round"/>`,
    )
    .join('\n  ');
}

function vectorLayers(layers) {
  return layers
    .map((l) =>
      l.fill
        ? `    <path android:pathData="${l.d}" android:fillColor="${l.fill}" />`
        : `    <path android:pathData="${l.d}" android:strokeColor="${l.stroke}" android:strokeWidth="${l.width}"\n        android:strokeLineCap="round" android:strokeLineJoin="round" />`,
    )
    .join('\n');
}

/** Legacy icon: the central 72x72 of the 108 grid on a green rounded square or circle. */
function legacySvg(shape, size) {
  const bg =
    shape === 'round'
      ? `<circle cx="54" cy="54" r="35" fill="${GREEN}"/>`
      : `<rect x="19" y="19" width="70" height="70" rx="13" fill="${GREEN}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="18 18 72 72">
  ${bg}
  ${svgLayers(FOREGROUND)}
</svg>
`;
}

const vectorHeader = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by resources/render-icons.mjs from resources/icon-shapes.mjs. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
`;

writeFileSync(join(here, 'icon.svg'), legacySvg('square', 512));
mkdirSync(join(res, 'drawable'), { recursive: true });
writeFileSync(join(res, 'drawable', 'ic_launcher_foreground.xml'), `${vectorHeader}${vectorLayers(FOREGROUND)}\n</vector>\n`);
writeFileSync(join(res, 'drawable', 'ic_launcher_monochrome.xml'), `${vectorHeader}${vectorLayers(MONOCHROME)}\n</vector>\n`);

const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/opt/node-tools/node_modules/playwright');
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  for (const [density, px] of Object.entries(densities)) {
    const dir = join(res, `mipmap-${density}`);
    mkdirSync(dir, { recursive: true });
    for (const [shape, file] of [
      ['square', 'ic_launcher.png'],
      ['round', 'ic_launcher_round.png'],
    ]) {
      await page.setViewportSize({ width: px, height: px });
      await page.setContent(
        `<html><body style="margin:0;background:transparent">${legacySvg(shape, px)}</body></html>`,
      );
      await page.locator('svg').screenshot({ path: join(dir, file), omitBackground: true });
    }
  }
  // A large preview for the README / Play listing.
  await page.setViewportSize({ width: 512, height: 512 });
  await page.setContent(`<html><body style="margin:0;background:transparent">${legacySvg('square', 512)}</body></html>`);
  await page.locator('svg').screenshot({ path: join(here, 'icon-512.png'), omitBackground: true });
} finally {
  await browser.close();
}
console.log('icons written');
