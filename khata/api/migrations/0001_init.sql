-- Kadan Kanakku server schema (Cloudflare D1 / SQLite). Forward-only migrations; never drop in the same release.
-- Money is INTEGER paise. Ledger rows are append-only. Sync ordering comes only from `changelog.seq`.

CREATE TABLE shops (
  id          TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  upi_id      TEXT,
  lang        TEXT NOT NULL DEFAULT 'ta' CHECK (lang IN ('ta','en')),
  sync_epoch  TEXT NOT NULL,              -- random UUID; changed after any restore so phones reset their cursor and re-push
  created_at  TEXT NOT NULL
);

CREATE TABLE devices (
  id              TEXT PRIMARY KEY,        -- generated by the server at /pair
  shop_id         TEXT NOT NULL REFERENCES shops(id),
  name            TEXT NOT NULL,
  role            TEXT NOT NULL CHECK (role IN ('owner','staff')),
  token_hash      TEXT NOT NULL UNIQUE,    -- hex sha256(token || PEPPER)
  created_at      TEXT NOT NULL,
  last_seen_at    TEXT,
  revoked_at      TEXT,
  wipe_on_revoke  INTEGER NOT NULL DEFAULT 0,
  requests_day    TEXT,                    -- UTC day of requests_today
  requests_today  INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX devices_shop ON devices(shop_id);

CREATE TABLE pair_codes (
  code_hash   TEXT PRIMARY KEY,            -- hex sha256(normalised code || PEPPER)
  shop_id     TEXT NOT NULL REFERENCES shops(id),
  role        TEXT NOT NULL CHECK (role IN ('owner','staff')),
  kind        TEXT NOT NULL CHECK (kind IN ('pair','setup','recovery')),
  issued_by   TEXT NOT NULL,               -- device id, or 'setup'
  created_at  TEXT NOT NULL,
  expires_at  TEXT,                        -- NULL for recovery codes
  used_at     TEXT,
  used_by     TEXT
);
CREATE INDEX pair_codes_shop ON pair_codes(shop_id, kind, used_at);

-- Wrong /pair guesses per UTC day. A throttle, never a lockout, never burns codes.
CREATE TABLE pair_failures (
  day              TEXT PRIMARY KEY,
  count            INTEGER NOT NULL DEFAULT 0,
  next_allowed_at  TEXT
);

-- Named counters per shop (customer_code).
CREATE TABLE seq (
  shop_id  TEXT NOT NULL,
  name     TEXT NOT NULL,
  value    INTEGER NOT NULL,
  PRIMARY KEY (shop_id, name)
);

CREATE TABLE code_blocks (
  shop_id      TEXT NOT NULL,
  block_start  INTEGER NOT NULL,
  block_end    INTEGER NOT NULL,
  device_id    TEXT NOT NULL,
  issued_at    TEXT NOT NULL,
  PRIMARY KEY (shop_id, block_start)
);

CREATE TABLE customers (
  id           TEXT PRIMARY KEY,
  shop_id      TEXT NOT NULL REFERENCES shops(id),
  code         INTEGER NOT NULL,
  name         TEXT NOT NULL,
  search_name  TEXT,
  phone        TEXT,
  note         TEXT,
  archived_at  TEXT,
  erased_at    TEXT,                       -- terminal; set only by POST /customers/:id/erase
  created_at   TEXT NOT NULL,
  updated_at   TEXT NOT NULL,
  updated_by   TEXT NOT NULL,
  received_at  TEXT NOT NULL,              -- server clock of the last accepted write
  UNIQUE (shop_id, code)
);
CREATE INDEX customers_phone ON customers(shop_id, phone);

CREATE TABLE entries (
  id                 TEXT PRIMARY KEY,
  shop_id            TEXT NOT NULL REFERENCES shops(id),
  customer_id        TEXT NOT NULL REFERENCES customers(id),
  kind               TEXT NOT NULL CHECK (kind IN ('GIVE','RECEIVE','WRITEOFF','REVERSAL')),
  amount_paise       INTEGER NOT NULL CHECK (amount_paise > 0),
  delta_paise        INTEGER NOT NULL,
  biz_date           TEXT NOT NULL,
  note               TEXT,
  mode               TEXT CHECK (mode IN ('CASH','UPI','OTHER')),
  reverses_entry_id  TEXT REFERENCES entries(id),
  device_id          TEXT NOT NULL,
  created_at         TEXT NOT NULL,
  received_at        TEXT NOT NULL,
  CHECK ((kind = 'GIVE' AND delta_paise = amount_paise)
      OR (kind IN ('RECEIVE','WRITEOFF') AND delta_paise = -amount_paise)
      OR (kind = 'REVERSAL' AND reverses_entry_id IS NOT NULL AND abs(delta_paise) = amount_paise))
);
CREATE INDEX entries_cust ON entries(customer_id, biz_date, created_at, id);
CREATE INDEX entries_day  ON entries(shop_id, biz_date);
CREATE UNIQUE INDEX entries_once ON entries(reverses_entry_id) WHERE reverses_entry_id IS NOT NULL;

-- Append-only change log: the ONLY ordering the sync protocol uses. One row per accepted insert/update.
CREATE TABLE changelog (
  seq          INTEGER PRIMARY KEY AUTOINCREMENT,
  shop_id      TEXT NOT NULL,
  tbl          TEXT NOT NULL CHECK (tbl IN ('customers','entries')),
  row_id       TEXT NOT NULL,
  device_id    TEXT NOT NULL,              -- author; /pull skips the caller's own rows
  received_at  TEXT NOT NULL
);
CREATE INDEX changelog_shop ON changelog(shop_id, seq);
CREATE INDEX changelog_row  ON changelog(shop_id, row_id, seq);
